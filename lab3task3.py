import math

print('Введите Xbeg, Xend, Dx и Eps (точность)')
xb = float(input('Xbeg = '))
xe = float(input('Xend = '))
dx = float(input('Dx = '))
eps = float(input('Eps = '))

print("+----------+----------+----------+")
print("I    X     I    Y     I    N     I")
print("+----------+----------+----------+")

xt = xb
while xt <= xe:
    # проверка ОДЗ: функция существует только от -3 до 1
    if xt <= -3 or xt >= 1:
        print(f"I {xt:8.2f} I  Ошибка (вне ОДЗ)  I")
    else:
        # начинаем суммировать ряд
        n = 0
        an = 0.5  # первый член ряда (при n=0: (-1)^0 * (x+1)^0 / 2^1 = 1/2)
        y = an

        # цикл для суммирования (пока модуль члена ряда больше точности)
        while abs(an) >= eps:
            k = -(xt + 1) / 2  # наш коэффициент
            an = an * k  # вычисляем следующий член
            y = y + an  # добавляем в общую сумму
            n = n + 1  # увеличиваем счетчик членов

        print(f"I {xt:8.2f} I {y:8.4f} I {n:8d} I")

    xt += dx

print("+----------+----------+----------+")